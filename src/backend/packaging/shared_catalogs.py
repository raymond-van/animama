"""Refresh or verify generated backend copies of frontend-owned product catalogs and guidance."""

from __future__ import annotations

import argparse
from pathlib import Path

# Package resource name (under src/backend/animama/resources) to its canonical source.
CATALOG_INPUTS = {
    "pocket-voice-selection.json": "scripts/voices/selection.json",
    "animation-manifest.json": "src/frontend/web/src/assets/vrm/animations/manifest.json",
    # The authoring joint table, written by `node scripts/authoring-joints.mjs --write` in src/frontend/web.
    "authoring/joints.md": "src/frontend/web/src/lib/avatar/motion-authoring/authoring-joints.generated.md",
}


def sync_catalogs(root: Path, *, write: bool = False) -> None:
    """Require identical canonical and generated bytes; write only on request."""
    for name, relative in CATALOG_INPUTS.items():
        source = root / relative
        destination = root / "src/backend/animama/resources" / name
        payload = source.read_bytes()
        if write:
            destination.write_bytes(payload)
        elif not destination.is_file() or destination.read_bytes() != payload:
            raise ValueError(
                f"Generated shared catalog differs from {relative}; run "
                "uv run --no-sync python src/backend/packaging/shared_catalogs.py --write"
            )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Refresh generated package copies")
    arguments = parser.parse_args()
    sync_catalogs(Path(__file__).resolve().parents[3], write=arguments.write)
